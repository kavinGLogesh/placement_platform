/**
 * Calculates optimal column widths for Excel sheets based on header and data content length
 */
export const calculateExcelColumnWidths = (payload: ExportDataPayload): { wch: number }[] => {
  return payload.columns.map((col) => {
    let maxLen = col.header.length;
    for (const row of payload.data) {
      const val = row[col.key];
      if (val !== undefined && val !== null) {
        const str = typeof val === 'boolean' ? (val ? 'PASSED' : 'FAILED') : String(val);
        if (str.length > maxLen) maxLen = str.length;
      }
    }
    return { wch: Math.min(65, Math.max(maxLen + 3, col.width || 12)) };
  });
};

/**
 * Generates an Excel (.xlsx) file buffer from report data
 */
export const generateExcelBuffer = (payload: ExportDataPayload): Buffer => {
  const wb = XLSX.utils.book_new();

  // 1. Build Title & Metadata Rows
  const sheetRows: any[][] = [];
  sheetRows.push([payload.institutionName.toUpperCase()]);
  sheetRows.push([payload.reportTitle]);
  sheetRows.push([
    `Generated On: ${payload.reportDate} | Generated By: ${payload.generatedBy} | Total Records: ${payload.data.length}`,
  ]);

  // Filters
  const filterEntries = Object.entries(payload.appliedFilters)
    .filter(([, v]) => v !== undefined && v !== '')
    .map(([k, v]) => `${k}: ${v}`);
  if (filterEntries.length > 0) {
    sheetRows.push([`Active Filters: ${filterEntries.join(' | ')}`]);
  } else {
    sheetRows.push(['Active Filters: None (All Academic Records)']);
  }

  // Summary Metrics (if available)
  if (payload.summaryMetrics && Object.keys(payload.summaryMetrics).length > 0) {
    sheetRows.push([]);
    sheetRows.push(['SUMMARY KEY PERFORMANCE INDICATORS']);
    Object.entries(payload.summaryMetrics).forEach(([k, v]) => {
      sheetRows.push([k, v]);
    });
  }

  sheetRows.push([]); // Empty spacer row

  // Data Table Headers
  const headerRowIndex = sheetRows.length;
  const headers = payload.columns.map((col) => col.header);
  sheetRows.push(headers);

  // Data Rows
  payload.data.forEach((item) => {
    const row = payload.columns.map((col) => {
      const val = item[col.key];
      if (val === undefined || val === null) return '';
      if (typeof val === 'boolean') return val ? 'PASSED' : 'FAILED';
      if (typeof val === 'number') return val;
      return String(val);
    });
    sheetRows.push(row);
  });

  const ws = XLSX.utils.aoa_to_sheet(sheetRows);

  // Set intelligent dynamic column widths
  ws['!cols'] = calculateExcelColumnWidths(payload);

  // Add auto-filter to data headers
  if (payload.data.length > 0 && payload.columns.length > 0) {
    const startCol = XLSX.utils.encode_col(0);
    const endCol = XLSX.utils.encode_col(payload.columns.length - 1);
    const startRow = headerRowIndex + 1;
    const endRow = sheetRows.length;
    ws['!autofilter'] = { ref: `${startCol}${startRow}:${endCol}${endRow}` };
  }

  XLSX.utils.book_append_sheet(wb, ws, 'Report_Data');
  return XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
};

/**
 * Generates an RFC-4180 CSV buffer from report data with UTF-8 BOM
 */
export const generateCsvBuffer = (payload: ExportDataPayload): Buffer => {
  const lines: string[] = [];

  // Metadata comments
  lines.push(`# ${payload.institutionName}`);
  lines.push(`# ${payload.reportTitle}`);
  lines.push(`# Generated: ${payload.reportDate} by ${payload.generatedBy} | Total Records: ${payload.data.length}`);

  const filterEntries = Object.entries(payload.appliedFilters)
    .filter(([, v]) => v !== undefined && v !== '')
    .map(([k, v]) => `${k}=${v}`);
  if (filterEntries.length > 0) {
    lines.push(`# Filters: ${filterEntries.join(', ')}`);
  }

  if (payload.summaryMetrics) {
    const summaryStr = Object.entries(payload.summaryMetrics)
      .map(([k, v]) => `${k}: ${v}`)
      .join(' | ');
    lines.push(`# Summary: ${summaryStr}`);
  }

  lines.push(''); // blank line

  // Escape helper for CSV RFC-4180
  const escapeCsv = (val: any): string => {
    if (val === undefined || val === null) return '""';
    if (typeof val === 'boolean') return val ? '"PASSED"' : '"FAILED"';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  };

  // Headers
  lines.push(payload.columns.map((c) => escapeCsv(c.header)).join(','));

  // Rows
  payload.data.forEach((item) => {
    const row = payload.columns.map((col) => escapeCsv(item[col.key]));
    lines.push(row.join(','));
  });

  // Include UTF-8 BOM so Excel on Windows opens CSV without encoding corruption
  const csvContent = '\uFEFF' + lines.join('\r\n');
  return Buffer.from(csvContent, 'utf-8');
};

/**
 * Calculates optimal column widths for PDFKit table layout,
 * ensuring no awkward wrapping for headers and proportional distribution for text columns.
 */
export const calculateOptimalPdfColumnWidths = (
  doc: PDFKit.PDFDocument,
  columns: ExportColumnDef[],
  usableWidth: number
): number[] => {
  doc.font('Helvetica-Bold').fontSize(6.5);
  const minWidths = columns.map((col) => {
    const headerW = doc.widthOfString(col.header.toUpperCase()) + 14;
    const k = col.key.toLowerCase();
    let contentMin = 42;
    if (k === 'rank') contentMin = 36;
    else if (k.includes('dept') || k === 'departmentcode') contentMin = 48;
    else if (k.includes('course') || k === 'coursecode') contentMin = 46;
    else if (k.includes('section') || k === 'sectionname') contentMin = 40;
    else if (k.includes('marks') || k === 'totalmarks' || k === 'obtainedmarks') contentMin = 48;
    else if (k.includes('percentage') || k === 'accuracy' || k.includes('rate') || k.includes('score')) contentMin = 50;
    else if (k === 'ispassed' || k === 'overallpassed' || k === 'resulttext' || k === 'resultstatus' || k.includes('status')) contentMin = 56;
    else if (k === 'registernumber' || k.includes('register')) contentMin = 74;
    else if (k.includes('date') || k.includes('submittedat') || k.includes('scheduleddate')) contentMin = 78;
    else if (k.includes('studentname') || k.includes('candidatename') || col.header.toLowerCase().includes('student name')) contentMin = 100;
    else if (k.includes('assessment') || k.includes('title') || k.includes('snippet') || k.includes('topic') || k.includes('challenge')) contentMin = 120;
    else if (k.includes('email')) contentMin = 105;
    return Math.max(headerW, contentMin);
  });

  const totalMin = minWidths.reduce((a, b) => a + b, 0);

  if (totalMin >= usableWidth) {
    const scale = usableWidth / totalMin;
    return minWidths.map((w) => w * scale);
  }

  const extra = usableWidth - totalMin;
  const flexWeights = columns.map((col) => {
    const k = col.key.toLowerCase();
    if (k.includes('assessment') || k.includes('title') || k.includes('topic') || k.includes('comparison') || k.includes('challenge')) return 4;
    if (k.includes('studentname') || k.includes('candidatename') || k.includes('email')) return 3;
    if (k.includes('date') || k.includes('evaluator')) return 1.5;
    return 1;
  });

  const totalFlex = flexWeights.reduce((a, b) => a + b, 0);
  return minWidths.map((minW, i) => minW + extra * (flexWeights[i] / totalFlex));
};

/**
 * Determines text alignment for a column
 */
function getColAlignment(col: ExportColumnDef): 'left' | 'center' | 'right' {
  if (col.format === 'percentage' || col.format === 'number') return 'right';
  const k = col.key.toLowerCase();
  if (
    k === 'rank' ||
    k === 'ispassed' ||
    k === 'overallpassed' ||
    k === 'resulttext' ||
    k === 'resultstatus' ||
    k === 'attendancestatus' ||
    k === 'language' ||
    k === 'difficulty' ||
    k === 'status'
  ) {
    return 'center';
  }
  if (
    k.includes('percentage') ||
    k.includes('accuracy') ||
    k.includes('marks') ||
    k.includes('count') ||
    k.includes('time') ||
    k.includes('rate') ||
    k.includes('score')
  ) {
    return 'right';
  }
  return 'left';
}

/**
 * Formats a cell value into clean readable text
 */
function formatCellValue(val: any): string {
  if (val === undefined || val === null) return '-';
  if (typeof val === 'boolean') return val ? 'PASSED' : 'FAILED';
  if (typeof val === 'number') return String(val);
  return String(val).trim() || '-';
}

/**
 * Generates an executive-grade PDF buffer using PDFKit with responsive KPI grid,
 * dynamic text wrapping, repeating table headers, and clean multi-page pagination.
 */
export const generatePdfBuffer = async (payload: ExportDataPayload): Promise<Buffer> => {
  return new Promise((resolve, reject) => {
    try {
      // Landscape A4 for wide reports (>= 5 columns), portrait for compact reports (< 5 columns)
      const isLandscape = payload.columns.length >= 5;
      const pageWidth = isLandscape ? 841.89 : 595.28;
      const pageHeight = isLandscape ? 595.28 : 841.89;
      const margin = 36;
      const usableWidth = pageWidth - margin * 2;
      const maxY = pageHeight - margin - 22; // 22pt reserved for bottom footer

      const doc = new PDFDocument({
        size: 'A4',
        layout: isLandscape ? 'landscape' : 'portrait',
        margin: 36,
        bufferPages: true,
      });

      const chunks: Buffer[] = [];
      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', (err) => reject(err));

      // -----------------------------------------------------------------------
      // 1. HEADER BANNER (Page 1)
      // -----------------------------------------------------------------------
      const bannerHeight = 44;
      doc.rect(margin, margin, usableWidth, bannerHeight).fill('#1e1b4b');
      // Left vertical indigo accent stripe
      doc.rect(margin, margin, 4, bannerHeight).fill('#4f46e5');

      // Institution Name
      doc
        .fillColor('#ffffff')
        .font('Helvetica-Bold')
        .fontSize(12)
        .text(payload.institutionName.toUpperCase(), margin + 14, margin + 8, {
          width: usableWidth - 170,
          ellipsis: true,
        });

      // Report Title
      doc
        .fillColor('#c7d2fe')
        .font('Helvetica')
        .fontSize(9)
        .text(payload.reportTitle, margin + 14, margin + 25, {
          width: usableWidth - 170,
          ellipsis: true,
        });

      // Right-side Verification Badge
      doc
        .fillColor('#94a3b8')
        .font('Helvetica-Bold')
        .fontSize(7)
        .text('CAREER OS VERIFIED', margin + usableWidth - 150, margin + 11, {
          width: 140,
          align: 'right',
        });
      doc
        .fillColor('#e2e8f0')
        .font('Helvetica')
        .fontSize(7.5)
        .text(`Total Records: ${payload.data.length}`, margin + usableWidth - 150, margin + 23, {
          width: 140,
          align: 'right',
        });

      let currentY = margin + bannerHeight + 8;

      // -----------------------------------------------------------------------
      // 2. METADATA & FILTERS BAR (Page 1)
      // -----------------------------------------------------------------------
      const metaBoxY = currentY;
      const metaBoxHeight = 28;
      doc.rect(margin, metaBoxY, usableWidth, metaBoxHeight).fill('#f8fafc');
      doc.rect(margin, metaBoxY, usableWidth, metaBoxHeight).stroke('#e2e8f0');

      const filterList = Object.entries(payload.appliedFilters)
        .filter(([, v]) => v !== undefined && v !== '')
        .map(([k, v]) => `${k}: ${v}`)
        .join(' | ');

      // Line 1: Generation Details
      doc
        .fillColor('#475569')
        .font('Helvetica')
        .fontSize(7)
        .text(`Generated: ${payload.reportDate} • Generated By: ${payload.generatedBy}`, margin + 8, metaBoxY + 5, {
          width: usableWidth * 0.65,
          ellipsis: true,
        });

      doc
        .fillColor('#64748b')
        .font('Helvetica-Bold')
        .fontSize(6.5)
        .text('Official Placement & Merit Record', margin + usableWidth * 0.65, metaBoxY + 5, {
          width: usableWidth * 0.35 - 8,
          align: 'right',
        });

      // Line 2: Applied Filters Across Full Width
      doc
        .fillColor('#334155')
        .font('Helvetica')
        .fontSize(7)
        .text(`Active Scope & Filters: ${filterList || 'All Academic Records'}`, margin + 8, metaBoxY + 16, {
          width: usableWidth - 16,
          ellipsis: true,
        });

      currentY += metaBoxHeight + 8;

      // -----------------------------------------------------------------------
      // 3. RESPONSIVE KPI METRICS CARDS GRID (Requirement 1)
      // -----------------------------------------------------------------------
      if (payload.summaryMetrics && Object.keys(payload.summaryMetrics).length > 0) {
        const entries = Object.entries(payload.summaryMetrics);
        const numCards = entries.length;

        // Symmetric balanced grid solver:
        let cardsPerRow = 1;
        if (isLandscape) {
          if (numCards <= 6) cardsPerRow = numCards;
          else if (numCards <= 8) cardsPerRow = 4;
          else if (numCards <= 10) cardsPerRow = 5;
          else cardsPerRow = 6;
        } else {
          if (numCards <= 3) cardsPerRow = numCards;
          else if (numCards === 4) cardsPerRow = 2;
          else if (numCards <= 6) cardsPerRow = 3;
          else cardsPerRow = 3;
        }

        const gap = 8;
        const cardWidth = (usableWidth - (cardsPerRow - 1) * gap) / cardsPerRow;
        const cardHeight = 34;

        for (let i = 0; i < numCards; i++) {
          const colIndex = i % cardsPerRow;
          const rowIndex = Math.floor(i / cardsPerRow);
          const cardX = margin + colIndex * (cardWidth + gap);
          const cardY = currentY + rowIndex * (cardHeight + gap);
          const [k, v] = entries[i];

          // Card Background & Subtle Border
          doc.rect(cardX, cardY, cardWidth, cardHeight).fill('#f8fafc');
          doc.rect(cardX, cardY, cardWidth, cardHeight).stroke('#e2e8f0');

          // Left Indigo Accent Stripe
          doc.rect(cardX, cardY, 3.5, cardHeight).fill('#4f46e5');

          // Metric Label
          doc
            .fillColor('#64748b')
            .font('Helvetica-Bold')
            .fontSize(6.5)
            .text(k.toUpperCase(), cardX + 8, cardY + 5.5, {
              width: cardWidth - 14,
              ellipsis: true,
              lineBreak: false,
            });

          // Metric Value
          doc
            .fillColor('#0f172a')
            .font('Helvetica-Bold')
            .fontSize(10.5)
            .text(String(v), cardX + 8, cardY + 16.5, {
              width: cardWidth - 14,
              ellipsis: true,
              lineBreak: false,
            });
        }

        const totalRows = Math.ceil(numCards / cardsPerRow);
        currentY += totalRows * (cardHeight + gap) + 6;
      }

      // -----------------------------------------------------------------------
      // 4. COLUMN WIDTH DISTRIBUTION & PROPORTIONS (Requirements 2, 3, 9)
      // -----------------------------------------------------------------------
      const colWidths = calculateOptimalPdfColumnWidths(doc, payload.columns, usableWidth);

      // Table Header Renderer (Requirement 5)
      const tableHeaderHeight = 20;
      const renderTableHeader = (yPos: number) => {
        doc.rect(margin, yPos, usableWidth, tableHeaderHeight).fill('#1e1b4b');
        doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(6.5);
        let currentX = margin;
        payload.columns.forEach((col, idx) => {
          const align = getColAlignment(col);
          doc.text(col.header.toUpperCase(), currentX + 4, yPos + 6, {
            width: colWidths[idx] - 8,
            align,
            ellipsis: true,
            lineBreak: false,
          });
          currentX += colWidths[idx];
        });
      };

      // Helper to compute dynamic row height based on text wrapping
      const calculateRowHeight = (row: Record<string, any>): number => {
        let maxTextHeight = 10;
        payload.columns.forEach((col, idx) => {
          const text = formatCellValue(row[col.key]);
          const cellWidth = colWidths[idx] - 8;
          doc.font('Helvetica').fontSize(6.8);
          const h = doc.heightOfString(text, { width: cellWidth, lineGap: 1 });
          if (h > maxTextHeight) {
            maxTextHeight = h;
          }
        });
        return Math.min(48, Math.max(17, Math.ceil(maxTextHeight + 7)));
      };

      // Initial table header on page 1
      renderTableHeader(currentY);
      currentY += tableHeaderHeight;

      // -----------------------------------------------------------------------
      // 5. DATA ROWS WITH DYNAMIC HEIGHT & OVERFLOW PAGINATION (Requirements 2, 5, 6, 7)
      // -----------------------------------------------------------------------
      if (payload.data.length === 0) {
        // Empty State Banner
        doc.rect(margin, currentY, usableWidth, 32).fill('#ffffff');
        doc.rect(margin, currentY, usableWidth, 32).stroke('#e2e8f0');
        doc
          .fillColor('#64748b')
          .font('Helvetica-Oblique')
          .fontSize(8)
          .text('No assessment records found matching the specified filter criteria.', margin, currentY + 11, {
            width: usableWidth,
            align: 'center',
          });
        currentY += 32;
      } else {
        payload.data.forEach((row, rowIdx) => {
          const rowHeight = calculateRowHeight(row);

          // Check if row exceeds printable height -> add new page before drawing
          if (currentY + rowHeight > maxY) {
            doc.addPage();

            // Running header on continuation page
            const contBannerHeight = 22;
            doc.rect(margin, margin, usableWidth, contBannerHeight).fill('#1e1b4b');
            doc.rect(margin, margin, 4, contBannerHeight).fill('#4f46e5');
            doc
              .fillColor('#ffffff')
              .font('Helvetica-Bold')
              .fontSize(8)
              .text(
                `${payload.institutionName.toUpperCase()} • ${payload.reportTitle}`,
                margin + 12,
                margin + 6,
                { width: usableWidth - 140, ellipsis: true }
              );
            doc
              .fillColor('#94a3b8')
              .font('Helvetica-Bold')
              .fontSize(7)
              .text('CONTINUATION ROSTER', margin + usableWidth - 130, margin + 7, {
                width: 120,
                align: 'right',
              });

            const nextHeaderY = margin + contBannerHeight + 4;
            renderTableHeader(nextHeaderY);
            currentY = nextHeaderY + tableHeaderHeight;
          }

          // Row background with alternating zebra striping
          const isEven = rowIdx % 2 === 0;
          const bgColor = isEven ? '#ffffff' : '#f8fafc';
          doc.rect(margin, currentY, usableWidth, rowHeight).fill(bgColor);
          doc.rect(margin, currentY, usableWidth, rowHeight).stroke('#e2e8f0');

          // Draw individual cells
          let currentX = margin;
          payload.columns.forEach((col, colIdx) => {
            const val = row[col.key];
            const text = formatCellValue(val);
            const align = getColAlignment(col);
            const cellWidth = colWidths[colIdx] - 8;

            // Special badge coloring for status/result values
            const k = col.key.toLowerCase();
            if (
              k === 'ispassed' ||
              k === 'overallpassed' ||
              k === 'resulttext' ||
              k === 'resultstatus' ||
              k === 'attendancestatus'
            ) {
              const isPass = text === 'PASSED' || text === 'PASS' || text === 'APPEARED';
              const isFail = text === 'FAILED' || text === 'FAIL' || text === 'NOT APPEARED';
              if (isPass) {
                doc.fillColor('#15803d').font('Helvetica-Bold').fontSize(6.8);
              } else if (isFail) {
                doc.fillColor('#b91c1c').font('Helvetica-Bold').fontSize(6.8);
              } else {
                doc.fillColor('#1e293b').font('Helvetica').fontSize(6.8);
              }
            } else {
              doc.fillColor('#1e293b').font('Helvetica').fontSize(6.8);
            }

            doc.text(text, currentX + 4, currentY + 4, {
              width: cellWidth,
              align,
              lineGap: 1,
            });

            currentX += colWidths[colIdx];
          });

          currentY += rowHeight;
        });
      }

      // -----------------------------------------------------------------------
      // 6. FOOTER STAMPING & EXACT PAGE NUMBERS (Requirements 7, 8)
      // -----------------------------------------------------------------------
      const range = doc.bufferedPageRange();
      for (let i = 0; i < range.count; i++) {
        doc.switchToPage(i);
        // CRITICAL: Disable bottom margin during footer stamping so PDFKit does not add phantom pages
        doc.page.margins.bottom = 0;
        const footerY = pageHeight - margin + 4;

        // Divider rule
        doc
          .strokeColor('#cbd5e1')
          .lineWidth(0.5)
          .moveTo(margin, footerY - 4)
          .lineTo(margin + usableWidth, footerY - 4)
          .stroke();

        // Left note
        doc
          .fillColor('#64748b')
          .font('Helvetica')
          .fontSize(6.5)
          .text(
            'Official Verification Document • Directorate of Placement & Career Development',
            margin,
            footerY,
            { width: usableWidth * 0.5, align: 'left', lineBreak: false }
          );

        // Right page number & timestamp
        doc
          .fillColor('#64748b')
          .font('Helvetica')
          .fontSize(6.5)
          .text(
            `Page ${i + 1} of ${range.count} • Generated: ${payload.reportDate}`,
            margin + usableWidth * 0.5,
            footerY,
            { width: usableWidth * 0.5, align: 'right', lineBreak: false }
          );
      }

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};

